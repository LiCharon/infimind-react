/**
 * 构建 Agent 2 的用户消息
 * @param {object} params
 * @param {string} params.contractText - 原始合同文本
 * @param {string} params.analysisReport - Agent 1 的分析报告
 * @param {Array<{name: string, content: string}>} params.templates - 知识库检索到的模版
 * @param {string} params.userInstruction - 用户在 Step 2 输入的额外关注点
 * @returns {string}
 */
export function buildReviewUserMessage({ contractText, analysisReport, templates, userInstruction }) {
  const hasInstruction = userInstruction && userInstruction.trim().length > 0

  let templateSection = ''
  if (templates && templates.length > 0) {
    templateSection = '\n\n### 知识库对照资料\n'
    templates.forEach((t, i) => {
      // 每个模版最多取 2500 字，避免输入过大导致请求中断
      const snippet = t.content ? t.content.slice(0, 2500) : '(模版内容暂缺)'
      const role = t.reference_role || 'reference'
      const roleLabel = role === 'excellent_template' ? '优秀/标准模板（正向对照）' : role === 'annotated_case' ? '已批注风险案例（反例）' : '普通参考资料'
      const notes = t.review_notes ? `\n使用说明：${t.review_notes}` : ''
      templateSection += `\n**资料${i + 1}：${t.name}｜${roleLabel}**${notes}\n${snippet}\n`
    })
    templateSection += '\n注：以上资料仅供结构、风险模式和条款参考，请以实际法律法规和交易事实为准。\n'
  }

  const focusSection = hasInstruction
    ? `\n\n## 用户额外关注的侧重点\n${userInstruction.trim()}\n\n请重点针对以上侧重点进行深入分析。`
    : '\n\n## 用户额外关注的侧重点\n无特殊侧重点，请按通用标准完成合同审查。'

  return `## 原始合同文本

${contractText}

---

## 合同分析报告

${analysisReport}
${templateSection}
${focusSection}

请严格按照回答参考格式，从买方视角进行全面审查。`
}
