2. **签约依据与生效条款审查**
审查合同是否明确援引现行有效法律依据（如《中华人民共和国民法典》），是否存在引用旧法（如《合同法》）的情形；合同生效条件（签字盖章/附条件生效）、签署份数及持有方式是否约定，补充协议的效力及与主合同的衔接是否明确。分析这些内容与用户侧重点的关联程度及影响。
